package espencionato;

public class Estudante {
	
	private String nome;
	private String email;
	
	public Estudante(String nome, String email) {
		super();
		this.nome = nome;
		this.email = email;
	}
	
	public String getNome() {
		return nome;
	}
	public String getEmail() {
		return email;
	}
	
	
}
